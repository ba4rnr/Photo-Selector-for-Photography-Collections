package com.photoselector.core;

/**
 * 目标序列条目的来源，决定保存时它会有怎样的真实结局。
 */
public enum Origin {

    /**
     * 真实文件：本来就躺在目标文件夹里，是启动时扫描进来的。
     * 保存时对它的操作（重命名、删除）会动到磁盘上的真身。
     */
    EXISTING,

    /**
     * 待复制：从素材文件夹挑来、还没落到目标文件夹的。
     * 保存时执行复制；若它先被拖进了垃圾桶，则什么都不用做——
     * 它从头到尾只是一个"指针"，磁盘上没有东西可删。
     */
    PENDING
}
